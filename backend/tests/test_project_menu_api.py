    def test_clone_waits_for_brief_preview_mutation(self):
        with connection() as lock:
            lock.execute('SELECT pg_advisory_lock_shared(hashtextextended(%s,17))',(str(self.project),))
            timer=threading.Timer(0.3,lambda:lock.execute('SELECT pg_advisory_unlock_shared(hashtextextended(%s,17))',(str(self.project),)))
            timer.start()
            response=self.client.post(self.url+'/clone',json={'title':'after preview'})
            timer.join()
            self.assertEqual(response.status_code,201,response.text)
            self.projects.append(uuid.UUID(response.json()['id']))
