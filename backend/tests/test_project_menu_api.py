    def test_publish_badge_privacy_and_unpublish(self):
        self.client.patch(self.url,json={'visibility':'private'})
        self.assertEqual(self.client.patch(self.url,json={'published':True}).status_code,409)
        self.client.patch(self.url,json={'visibility':'public'})
        response=self.client.patch(self.url,json={'published':True});self.assertEqual(response.status_code,200,response.text)
        slug='menu-'+self.project.hex[:12]
        self.assertEqual(self.client.patch(self.url,json={'publish_slug':slug}).status_code,200)
        self.assertEqual(self.client.get('/api/sites/'+slug).status_code,200)
        public='/api/public/'+str(self.project);self.assertIn('data-atoms-badge',self.client.get(public+'?__atoms_frame=1').text)
        self.assertEqual(self.client.patch(self.url,json={'remove_badge':True,'favorite':True,'title':'new title'}).status_code,200)
        self.assertNotIn('data-atoms-badge',self.client.get(public+'?__atoms_frame=1').text)
        row=self.client.get(self.url).json();self.assertTrue(row['favorite']);self.assertEqual(row['title'],'new title')
        self.client.patch(self.url,json={'visibility':'private'});self.assertEqual(self.client.get(public).status_code,404);self.assertEqual(self.client.get('/api/sites/'+slug).status_code,404)
        self.client.patch(self.url,json={'visibility':'public'});self.assertEqual(self.client.get(public).status_code,200)
        self.client.patch(self.url,json={'published':False});self.assertEqual(self.client.get(public).status_code,404)
