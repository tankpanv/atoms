    def test_database_browser_real_rows_pagination_and_owner_isolation(self):
        listed=self.client.get(self.url+'/database/tables')
        self.assertEqual(listed.status_code,200,listed.text)
        self.assertEqual(listed.json()['tables'],[{'name':'items'}])
        with connection() as c:
            c.execute(sql.SQL('INSERT INTO {}.items(name) VALUES(%s)').format(sql.Identifier(names(self.project)[0])),('second',))
        first=self.client.get(self.url+'/database/tables',params={'table':'items','limit':1}).json()
        self.assertEqual(first['rows'][0]['name'],'original')
        self.assertTrue(first['has_more'])
        second=self.client.get(self.url+'/database/tables',params={'table':'items','limit':1,'offset':1}).json()
        self.assertEqual(second['rows'][0]['name'],'second')
        self.assertFalse(second['has_more'])
        self.assertEqual(self.client.get(self.url+'/database/tables',params={'table':'public.users'}).status_code,404)
        self.assertEqual(self.client.get(self.url+'/database/tables',params={'table':'items; DROP SCHEMA public'}).status_code,404)
        self.assertEqual(self.client.get(self.url+'/database/tables',params={'limit':101}).status_code,422)
        app.dependency_overrides[current_user]=lambda:{'id':uuid.uuid4(),'email':'foreign@example.test'}
        self.assertEqual(self.client.get(self.url+'/database/tables').status_code,404)

